"""Generate lean/CF.lean (Proposition CF, order-independent part) from lean/Confluence.lean by adding variables
(main agent, 2026-10-27). Usage: python gen_cf.py"""
src = open("../lean/Confluence.lean", encoding="utf-8").read()
body = src.split("/-- normal form: no redex anywhere -/")[0]
body = body.split("open T", 1)[1]
hdr = '''/-
  Proposition CF, order-independent part — machine-checked (main agent, 2026-10-27). Plain Lean 4 core.
  Generated by code/gen_cf.py from lean/Confluence.lean.
  S-terms with variables (opaque atoms). Reduction contracts one redex S x y z anywhere. Confluence is re-proved with
  variables (same proof as lean/Confluence.lean). A term is *head-normal* if its head is a variable, or S with at most
  two spine arguments (no head redex in any spine prefix).
  * `hnf_stable`: reducing a head-normal term keeps its head and arity and reduces the arguments position-wise.
  * `cf_control`: any two head-normal reducts of a term (reached by ANY evaluation orders) have the same head, the same
    number of arguments, and pairwise joinable arguments: which argument (or S) receives control, and with how many
    arguments, does not depend on the evaluation order. (That head reduction finds such a form whenever one exists is
    the standardization theorem, cited, not formalised here.)
-/

inductive T where
  | S : T
  | var : Nat → T
  | app : T → T → T
deriving DecidableEq, Repr

open T
'''


def rep(s, a, b):
    assert a in s, a[:70]
    return s.replace(a, b, 1)


body = rep(body, "inductive Par : T → T → Prop\n  | S : Par S S\n",
           "inductive Par : T → T → Prop\n  | S : Par S S\n  | var (n : Nat) : Par (var n) (var n)\n")
body = rep(body, "theorem par_refl : ∀ t : T, Par t t\n  | S => Par.S\n",
           "theorem par_refl : ∀ t : T, Par t t\n  | S => Par.S\n  | var n => Par.var n\n")
body = rep(body, "  induction h with\n  | S => exact RedStar.refl _\n  | app _ _ ih1 ih2 => exact redstar_app ih1 ih2",
           "  induction h with\n  | S => exact RedStar.refl _\n  | var n => exact RedStar.refl _\n  | app _ _ ih1 ih2 => exact redstar_app ih1 ih2")
body = rep(body, "def cd : T → T\n  | S => S\n", "def cd : T → T\n  | S => S\n  | var n => var n\n")
old_cd = body[body.index("theorem par_cd"):body.index("theorem par_diamond")]
new_cd = old_cd
new_cd = rep(new_cd, "  | S => exact Par.S\n", "  | S => exact Par.S\n  | var n => exact Par.var n\n")
extra = '''    | var n, hf, ihf =>
      show Par (app f' a') (app (cd (var n)) (cd a))
      exact Par.app ihf iha
    | app (var n) x, hf, ihf =>
      show Par (app f' a') (app (cd (app (var n) x)) (cd a))
      exact Par.app ihf iha
    | app (app (var n) x) y, hf, ihf =>
      show Par (app f' a') (app (cd (app (app (var n) x) y)) (cd a))
      exact Par.app ihf iha
'''
new_cd = rep(new_cd, "    | app S x, hf, ihf =>\n", extra + "    | app S x, hf, ihf =>\n")
body = body.replace(old_cd, new_cd)

tail = open("cf_tail.lean.txt", encoding="utf-8").read()
out = hdr + body + tail
open("../lean/CF.lean", "w", encoding="utf-8").write(out)
print("written", out.count("\n"), "lines")
