"""Refined certificate test: the 'finite' verdicts of a path model (leftmost or rightmost Böhm-tree path).

Joint model J = sub-magma of (path model x M35) generated by S. A path step from a node u (with an hnf):
 - u = S x or S x y:  child = x (leftmost) / last argument (rightmost)        -> proper subterm   ('dec')
 - u = S e1..em, m >= 3: hnf = S v (q v) where (S, q, v) is the final state of the tail chain of the last call
   App(H(S e1..e_{m-1}), e_m) (chain states (p, q, v), Theorem Q10). Leftmost child v; rightmost child q v.
   Leftmost: if the chain has length 0, v = e_m (proper subterm, 'dec'); otherwise v = q' v' is new ('new').
   Rightmost: q v is always new.
Abstractly the chain lives in the graph G_J (peel/refill edges over J, Theorem Q10); its states (a, b, beta) all have
class rho = s.a.b.beta = [u]. Final states are those with a = s. A final state with an incoming G_J edge can end a chain
of length >= 1. Path edges: kappa -> child class, labelled dec / new. If no 'new' edge lies inside an SCC of the path
graph restricted to the model's 'finite' classes with an hnf, every such path is finite.
Usage: python leftpathcert.py left|right
"""
import sys, collections
import networkx as nx
from verify_model import load

side = sys.argv[1]
P = load("../data/model36_leftpath.txt" if side == "left" else "../data/model19_rightpath.txt")
Mm = load("../data/model35_hn.txt")
sP, sM = P[0].index("S"), Mm[0].index("S")
def mul(x, y): return (int(P[2][x[0], y[0]]), int(Mm[2][x[1], y[1]]))
s = (sP, sM)
J = [s]; seen = {s}; i = 0
while i < len(J):
    a = J[i]; i += 1
    for b in J[:i]:
        for c in (mul(a, b), mul(b, a)):
            if c not in seen: seen.add(c); J.append(c)
inC = lambda k: P[1][k[0]] == 0 and Mm[1][k[1]] == 1          # model says 'path finite', node has an hnf
one = collections.defaultdict(list); two = collections.defaultdict(list)
for x in J:
    one[mul(s, x)].append(x)
    for y in J:
        two[mul(mul(s, x), y)].append((x, y))
# chain graph G_J restricted to states with rho in F_M (all reachable chain states of nodes with hnf)
indeg = collections.Counter()
states = [(a, b, be) for a in J for b in J for be in J if Mm[1][mul(mul(mul(s, a), b), be)[1]]]
Sset = set(states)
for (a, b, be) in states:
    for x in one.get(a, []):
        t = (x, be, mul(b, be))
        if t in Sset: indeg[t] += 1
    if a != s and a in two:
        for (a2, b2) in two.get(mul(a, be), []):
            if b2 == s: continue
            t = (a2, b2, mul(b, be))
            if t in Sset: indeg[t] += 1
print(f"{side}: joint classes {len(J)}, chain states {len(states)}, final states with in-edges "
      f"{sum(1 for st in states if st[0] == s and indeg[st])}")
PG = nx.DiGraph(); lab = collections.defaultdict(set)
def add(u, v, l):
    if inC(u) and inC(v):
        PG.add_edge(u, v); lab[(u, v)].add(l)
for x in J:                                   # syntactic hnf nodes
    add(mul(s, x), x, "dec")
    for y in J:
        add(mul(mul(s, x), y), x if side == "left" else y, "dec")
for (a, b, be) in states:                     # computed nodes: final chain states (s, b, be)
    if a != s: continue
    kap = mul(mul(mul(s, a), b), be)
    if side == "left":
        add(kap, be, "dec")                   # chain of length 0: v = e_m
        if indeg[(a, b, be)]: add(kap, be, "new")
    else:
        add(kap, mul(b, be), "new")
comp = {}
for k, scc in enumerate(nx.strongly_connected_components(PG)):
    for v in scc: comp[v] = k
bad = [(u, v) for (u, v), l in lab.items() if "new" in l and comp[u] == comp[v]]
sizes = sorted(collections.Counter(comp.values()).values(), reverse=True)[:5]
print(f"   path graph: {PG.number_of_nodes()} nodes, {PG.number_of_edges()} edges, largest SCCs {sizes}; 'new' edges inside SCCs: {len(bad)}")
for e in bad[:8]: print("     ", e, sorted(lab[e]))
