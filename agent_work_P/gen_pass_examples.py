"""Cross-check the Lean `pass` (agent_work_P/lean/ParTime.lean) against the Python ReplaceAll pass used throughout the
project (code/parallel_eval.step_fn): emit Lean `example`s  passN k t = u  for random S-terms t, with u computed in
Python; the Lean kernel checks each by `decide`.  Output: lean/PassCheck_tail.lean.txt"""
import random, sys
from ptools import *
rng = random.Random(20261027)
def rand_term(leaves):
    if leaves == 1: return 0
    k = rng.randint(1, leaves - 1)
    return hc.app(rand_term(k), rand_term(leaves - k))
def lean(t):
    if t == 0: return "S"
    return f"(app {lean(hc.L[t])} {lean(hc.R[t])})"
lines = ["", "/-! ## Cross-check: Lean `pass` = the project's Python ReplaceAll pass (code/parallel_eval.step_fn) on random terms",
         "    (generated by agent_work_P/gen_pass_examples.py; each instance is checked by the kernel with `decide`) -/", ""]
n = 0
while n < 30:
    t = rand_term(rng.randint(5, 11)); k = rng.randint(1, 4)
    u = t
    for _ in range(k): u = P(u)
    if size(u) > 60: continue
    lines.append(f"example : passN {k} {lean(t)} = {lean(u)} := by decide")
    n += 1
open("lean/PassCheck_tail.lean.txt", "w").write("\n".join(lines) + "\n")
print("wrote", n, "examples")
