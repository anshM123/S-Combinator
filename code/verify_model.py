"""Verify a candidate finite S-model (magma) for head-normalizability of S-terms.

Input: a 'cong' output file from sterm.exe (class list + product table).
Checks:
  (1) S-identity  s*x*y*z == x*z*(y*z)  for all classes x,y,z
  (2) every head normal form shape S, S x, S x y lands in F (the HN-classes)
  (3) the non-F classes are left-absorbing (bottom * x == bottom)
  (4) agreement with the brute-force census files enum_<n>.txt (hnf code column) for n = 1..nmax
"""
import sys, re
import numpy as np

def load(path):
    classes, hn, rows = [], [], []
    in_tab = False
    for line in open(path):
        if line.startswith("class "):
            m = re.match(r"class (\d+) HN=(\d) count (\d+) ctxHN (\d+) rep (\S+)", line)
            classes.append(m.group(5)); hn.append(int(m.group(2)))
        elif line.startswith("# product table"):
            in_tab = True
        elif line.startswith("#"):
            in_tab = False
        elif in_tab and line.strip():
            rows.append([int(v) for v in line.split()])
    tab = np.array(rows, dtype=np.int64)
    return classes, np.array(hn), tab

def main():
    path = sys.argv[1]; nmax = int(sys.argv[2]) if len(sys.argv) > 2 else 14
    datadir = sys.argv[3] if len(sys.argv) > 3 else "../data"
    reps, hn, tab = load(path)
    m = len(reps)
    assert tab.shape == (m, m), tab.shape
    assert (tab >= 0).all(), "table has unknown (-1) entries"
    s = reps.index("S")
    F = hn == 1
    # (1) S identity
    bad = 0
    for x in range(m):
        sx = tab[s, x]
        for y in range(m):
            sxy = tab[sx, y]
            lhs = tab[sxy]                        # vector over z
            rhs = tab[tab[x], tab[y]] if False else None
            for z in range(m):
                if lhs[z] != tab[tab[x, z], tab[y, z]]:
                    bad += 1
    print(f"classes={m}, S-class={s}, |F|={F.sum()}, S-identity violations={bad}")
    # (2) hnf shapes
    sh = [s] + [tab[s, x] for x in range(m)] + [tab[tab[s, x], y] for x in range(m) for y in range(m)]
    print("hnf shapes all in F:", all(F[v] for v in sh))
    # (3) bottom absorbing
    bots = [i for i in range(m) if not F[i]]
    print("non-F classes:", bots, "left-absorbing:", all(tab[b, x] == b for b in bots for x in range(m)),
          " right-mult of bottom:", sorted(set(int(tab[x, b]) for b in bots for x in range(m))))
    # generated sub-magma = all classes reachable from S
    seen = {s}; frontier = [s]
    while frontier:
        new = []
        for a in list(seen):
            for b in list(seen):
                c = int(tab[a, b])
                if c not in seen:
                    seen.add(c); new.append(c)
        frontier = new
    print("classes generated by S:", len(seen))
    # (4) census agreement
    cls = {1: np.array([s], dtype=np.int64)}
    for n in range(2, nmax + 1):
        parts = [tab[np.ix_(cls[i], cls[n - i])].ravel() for i in range(1, n)]
        cls[n] = np.concatenate(parts)
    for n in range(1, nmax + 1):
        try:
            f = open(f"{datadir}/enum_{n}.txt")
        except OSError:
            continue
        code = np.full(len(cls[n]), -99, dtype=np.int64)
        for line in f:
            if line.startswith("#"):
                continue
            p = line.split()
            code[int(p[0])] = int(p[1])
        pred = F[cls[n]]
        census = code == 1
        missing = (code == -99).sum()
        fp = int((pred & ~census).sum()); fn = int((~pred & census).sum())
        print(f"n={n}: terms={len(cls[n])} missing={missing} model-HN={int(pred.sum())} census-HN={int(census.sum())} "
              f"model says HN but census no-hnf-within-budget: {fp}; model says no-HN but census HN: {fn}")

if __name__ == "__main__":
    main()
