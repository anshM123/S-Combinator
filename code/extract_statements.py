def statement(src, name):
    m = re.search(r"^theorem " + re.escape(name) + r"\b(.*?):= ?(by|$|fun|\n|[A-Za-z])", src, re.S | re.M)
    if not m:
        return None
    text = "theorem " + name + m.group(1)
    return text.rstrip().rstrip(":").rstrip()


