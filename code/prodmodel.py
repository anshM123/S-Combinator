"""Structure of the candidate productivity model P39 (data/closure_prod_7_6.txt) and its relation to M35."""
import sys, numpy as np
from verify_model import load
from symb import parse, spine

P_reps, P_F, P = load("../data/closure_prod_7_6.txt")
M_reps, M_F, M = load("../data/model35_hn.txt")
nP, nM = len(P_reps), len(M_reps)
sP, sM = P_reps.index("S"), M_reps.index("S")

def ev(t, tab, s):
    if isinstance(t, str): return s
    return int(tab[ev(t[0], tab, s), ev(t[1], tab, s)])

def parse_full(r):
    # reps are printed with full parenthesisation of non-S arguments; symb.parse handles juxtaposition + parentheses
    return parse(r)

f = [ev(parse_full(r), M, sM) for r in P_reps]
hom = all(f[int(P[a, b])] == int(M[f[a], f[b]]) for a in range(nP) for b in range(nP))
print("P39 -> M35 map well defined as homomorphism:", hom, "| image size", len(set(f)))
print("productive classes map into HN classes:", all(M_F[f[a]] for a in range(nP) if P_F[a]))
bot = [a for a in range(nP) if not P_F[a]]
print("non-productive classes:", bot, "-> M35 classes", [f[a] for a in bot], "(M35 bottom has HN=0:", [int(M_F[f[a]]) for a in bot], ")")
# fibres of the map: which M35 classes split?
from collections import defaultdict
fib = defaultdict(list)
for a in range(nP): fib[f[a]].append(a)
print("M35 classes hit:", len(fib), " split classes:", {k: v for k, v in fib.items() if len(v) > 1})
# necessary closure conditions for a productivity model
s = sP
c1 = all((P_F[int(P[P[s, x], y])] == (P_F[x] and P_F[y])) for x in range(nP) for y in range(nP))
c2 = all((P_F[int(P[s, x])] == P_F[x]) for x in range(nP))
print("S x y productive <=> x,y productive (table):", c1, "| S x productive <=> x productive:", c2)
b = bot[0]
print("bottom two-sided absorbing:", all(int(P[b, x]) == b and int(P[x, b]) == b for x in range(nP)))
# context monoid aperiodicity: maps generated by x -> a*x and x -> x*a
gens = [tuple(int(P[a, x]) for x in range(nP)) for a in range(nP)] + [tuple(int(P[x, a]) for x in range(nP)) for a in range(nP)]
ident = tuple(range(nP))
mon = {ident}; frontier = [ident]
while frontier:
    new = []
    for g in frontier:
        for h in gens:
            c = tuple(h[g[x]] for x in range(nP))
            if c not in mon: mon.add(c); new.append(c)
    frontier = new
    if len(mon) > 200000: print("monoid too large"); break
def power(g, k):
    r = ident
    for _ in range(k): r = tuple(g[r[x]] for x in range(nP))
    return r
ap = max_idx = 0
aperiodic = True
for g in mon:
    seen = {}; r = ident; k = 0
    while r not in seen: seen[r] = k; r = tuple(g[r[x]] for x in range(nP)); k += 1
    period = k - seen[r]
    if period != 1: aperiodic = False
    max_idx = max(max_idx, seen[r])
print("context monoid size:", len(mon), " aperiodic:", aperiodic, " max index:", max_idx)

# partial homomorphism on productive classes: whenever a, b, ab are all productive, f(ab) = f(a) f(b)
bad = [(a, b) for a in range(nP) for b in range(nP)
       if P_F[a] and P_F[b] and P_F[int(P[a, b])] and f[int(P[a, b])] != int(M[f[a], f[b]])]
print("partial homomorphism on productive products: violations", len(bad))
# products of productive classes that are non-productive (where productivity is lost)
lost = [(a, b) for a in range(nP) for b in range(nP) if P_F[a] and P_F[b] and not P_F[int(P[a, b])]]
print("productive*productive -> bottom:", len(lost), "of", int(P_F.sum())**2)
# does the HN verdict of a productive-class product agree with M35? (a, b productive, ab bottom: is f(a)f(b) HN?)
hnlost = sum(1 for a, b in lost if M_F[int(M[f[a], f[b]])])
print("  of these, products that still have an hnf by M35:", hnlost)
