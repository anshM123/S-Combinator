"""Search for a finite non-idempotent type certificate for BEKW Question 10.

Theta = a finite set of types. V(S) = the valid S-axiom types in Theta; V(t u) = {B : (M -> B) in V(t), supp(M) <= V(u)}.
Every type in V(t) is derivable for t (induction), and a typable closed term head-normalises (derivation weight drops by
one per head step, see nitypes.py). So if every element (c, X) of the magma generated by (s, V(S)) in M35 x P(Theta)
with c in F has ok in X, then every M35-F term head-normalises: Question 10.
Theta starts from canonical derivations of all F terms with <= N0 leaves; each round adds the canonical types of the
representative terms of failing elements.
Usage: python nicert.py N0 ROUNDS [MAXELEMS]
"""
import sys, collections
from opencount import cl, F, M, s as S_CLASS
from nitypes import occurrence_types, OK, show_type, depth
from symb import trees, show

def valid_S(T):
    if T == OK: return True
    if T[0] != "a": return False
    Mx, R1 = T[1], T[2]
    if Mx == () and R1 == OK: return True                                  # S a : ok
    if R1 == OK or R1[0] != "a": return False
    My, R2 = R1[1], R1[2]
    if Mx == () and My == () and R2 == OK: return True                     # S a b : ok
    if len(Mx) != 1 or R2 == OK or R2[0] != "a": return False
    Mz, B = R2[1], R2[2]
    X = Mx[0]
    if X == OK or X[2] == OK: return False
    M1, M2, B2 = X[1], X[2][1], X[2][2]
    if B2 != B: return False
    if any(A == OK for A in My): return False
    if sorted(map(repr, (A[2] for A in My))) != sorted(map(repr, M2)): return False
    z = list(M1) + [N for A in My for N in A[1]]
    return sorted(map(repr, z)) == sorted(map(repr, Mz))

def collect(terms):
    types = set()
    for t in terms:
        occ = occurrence_types(t)
        if occ is None:
            return None, t
        for u, T in occ:
            types.add(T)
    return types, None

def check(theta, maxelems):
    tl = sorted(theta, key=repr); idx = {T: i for i, T in enumerate(tl)}
    arrows = [(i, idx[T[2]], frozenset(idx[A] for A in T[1])) for i, T in enumerate(tl)
              if T != OK and T[2] in idx and all(A in idx for A in T[1])]
    ok = idx[OK]
    VS = frozenset(i for i, T in enumerate(tl) if valid_S(T))
    by_res = collections.defaultdict(list)
    def mul(X, Y):
        return frozenset(r for (i, r, sup) in arrows if i in X and sup <= Y)
    start = (S_CLASS, VS)
    rep = {start: "S"}; elems = [start]; seen = {start}
    i = 0
    while i < len(elems):
        u = elems[i]; i += 1
        for j in range(i):
            v = elems[j]
            for (a, b) in ((u, v), (v, u)) if u != v else ((u, u),):
                w = (int(M[a[0], b[0]]), mul(a[1], b[1]))
                if w not in seen:
                    seen.add(w); elems.append(w); rep[w] = (rep[a], rep[b])
                    if len(elems) > maxelems:
                        return None, len(elems), tl
    fails = [w for w in elems if F[w[0]] and ok not in w[1]]
    return fails, len(elems), (tl, rep)

if __name__ == "__main__":
    N0, ROUNDS = int(sys.argv[1]), int(sys.argv[2])
    MAXE = int(sys.argv[3]) if len(sys.argv) > 3 else 200000
    base = [t for n in range(1, N0 + 1) for t in trees(n) if F[cl(t)]]
    theta, bad = collect(base)
    print(f"Theta from all F terms <= {N0} leaves: {len(theta)} types, max depth {max(map(depth, theta))}", flush=True)
    for rnd in range(ROUNDS):
        fails, ne, info = check(theta, MAXE)
        if fails is None:
            print(f"round {rnd}: magma exceeded {MAXE} elements", flush=True); break
        tl, rep = info
        print(f"round {rnd}: |Theta| = {len(theta)}, magma elements {ne}, failing F-elements {len(fails)}; their M35 classes {sorted(w[0] for w in fails)}", flush=True)
        if not fails:
            print("CERTIFICATE FOUND: every F element contains ok", flush=True)
            with open("../data/nicert_theta.txt", "w") as f:
                for T in tl: f.write(show_type(T) + "\n")
            break
        reps_t = sorted((rep[w] for w in fails), key=lambda t: len(repr(t)))
        print("   smallest failing representatives:", [show(t) for t in reps_t[:4]], flush=True)
        new, bad = collect(reps_t[:200])
        if new is None:
            print("   representative WITHOUT hnf (Q10 counterexample?):", show(bad), flush=True); break
        added = new - theta
        print(f"   adding {len(added)} types (max depth {max(map(depth, added), default=0)})", flush=True)
        if not added:
            print("   no new types: the failing elements are not repaired by canonical types", flush=True); break
        theta |= added
