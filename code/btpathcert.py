"""Can a Böhm-tree path stay forever inside a set C of joint classes?  (coarse certificate test)

Joint model = sub-magma of the product of the given S-models generated by the S classes.
A Böhm-tree step goes from a node u (with an hnf) to a component of its hnf.
  structural step: u is literally S x or S x y; the child is a proper subterm of u.
  computed step:   u has >= 3 arguments; its hnf is S c (b c) where S S b c is the configuration before the last
                   head step (the last step is [S, b, c] => [c, b.c]); children c and b c, with s.s.b.c = [u].
If no computed edge of the abstract graph lies inside a strongly connected component of the graph restricted to C,
every path inside C eventually takes structural steps only, hence is finite.
Usage: python btpathcert.py MODE   (MODE = c8 | c6 | left | right)
"""
import sys, collections
import numpy as np
import networkx as nx
from verify_model import load

def joint(paths):
    mods = [load(p) for p in paths]
    ss = tuple(m[0].index("S") for m in mods)
    def mul(x, y): return tuple(int(m[2][a, b]) for m, a, b in zip(mods, x, y))
    seen = {ss}; order = [ss]; i = 0
    while i < len(order):
        a = order[i]; i += 1
        for b in list(order[:i]):
            for c in (mul(a, b), mul(b, a)):
                if c not in seen: seen.add(c); order.append(c)
    return mods, ss, order, mul

MODE = sys.argv[1]
if MODE == "c8":       # B131 'finite' classes: no infinite path at all (all components)
    paths = ["../data/model131_btfinite.txt", "../data/model35_hn.txt"]
    mods, s, J, mul = joint(paths)
    inC = lambda k: mods[0][1][k[0]] == 1 and mods[1][1][k[1]] == 1
    sel = "all"
elif MODE == "c6":     # P39 bottom classes with an hnf: path following P-bottom components must end
    paths = ["../data/model39_productivity.txt", "../data/model35_hn.txt"]
    mods, s, J, mul = joint(paths)
    inC = lambda k: mods[0][1][k[0]] == 0 and mods[1][1][k[1]] == 1
    sel = "all"
elif MODE in ("left", "right"):
    paths = ["../data/model36_leftpath.txt" if MODE == "left" else "../data/model19_rightpath.txt",
             "../data/model35_hn.txt"]
    mods, s, J, mul = joint(paths)
    # in these models HN=1 marks 'path infinite'; a 'finite' verdict must be certified: C = model says finite, has hnf
    inC = lambda k: mods[0][1][k[0]] == 0 and mods[1][1][k[1]] == 1
    sel = "first" if MODE == "left" else "last"
print(f"{MODE}: joint classes {len(J)}, in C {sum(1 for k in J if inC(k))}")

G = nx.DiGraph(); kind = collections.defaultdict(set)
Jset = set(J)
s_ = s
for x in J:
    k1 = mul(s_, x)
    for y in J:
        k2 = mul(k1, y)
        # structural: node S x y -> components
        if inC(k2):
            tg = {"all": [x, y], "first": [x], "last": [y]}[sel]
            for c in tg:
                if inC(c): G.add_edge(k2, c); kind[(k2, c)].add("struct")
    if inC(k1):                       # node S x -> x
        if inC(x): G.add_edge(k1, x); kind[(k1, x)].add("struct")
# computed: node class kappa = s.s.b.c, children c (first) and b.c (second)
ss_ = mul(s_, s_)
for b in J:
    k_b = mul(ss_, b)
    for c in J:
        kap = mul(k_b, c)
        if not inC(kap): continue
        bc = mul(b, c)
        tg = {"all": [c, bc], "first": [c], "last": [bc]}[sel]
        for ch in tg:
            if inC(ch): G.add_edge(kap, ch); kind[(kap, ch)].add("comp")
comp = {}
for i, scc in enumerate(nx.strongly_connected_components(G)):
    for v in scc: comp[v] = i
bad = [(u, v) for (u, v), k in kind.items() if "comp" in k and comp[u] == comp[v]]
sizes = collections.Counter(comp.values())
print(f"   graph: {G.number_of_nodes()} nodes, {G.number_of_edges()} edges; largest SCCs {sorted(sizes.values(), reverse=True)[:5]}")
print(f"   computed edges inside an SCC: {len(bad)}")
for e in bad[:8]:
    print("     ", e, sorted(kind[e]))
